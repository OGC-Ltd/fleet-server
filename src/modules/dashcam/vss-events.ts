export function vssEvent(code: number): { name: string; group: string; severity: Severity } {
  const e = EVENTS[code]
  return e ? { name: e[0], group: e[1], severity: e[2] } : { name: `Alarm ${code}`, group: 'Other', severity: 'warning' }
}

const range = (a: number, b: number) => Array.from({ length: b - a + 1 }, (_, i) => a + i)
const CATEGORY = new Map<number, Category>()
const put = (cat: Category, codes: number[]) => { for (const c of codes) CATEGORY.set(c, cat) }
put('braking',   [12, 24, 25, 52, 53, 71, 212, 213, 214, 266, 267])
put('speeding',  [6, 7, 26, 27, 48, 54, 55, 106, 202, 203, 204, 205, 206])
put('driver',    [17, 51, 61, 62, 82, ...range(115, 134), 147, 148, ...range(251, 265)])
put('collision', [64, 69, 100, 102, 103, 104, 107, 109, 110, 111, 217, 218, ...range(135, 146)])
put('geofence',  [13, 14, 200, 201, 207, 208, 209, 215, 216])

/** The inbox chip an alarm code is filed under. */
export function vssCategory(code: number): Category {
  return CATEGORY.get(code) ?? 'other'
}
